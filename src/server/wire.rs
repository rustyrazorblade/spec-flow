//! The MCP wire shapes for the tools [`crate::server`] exposes — the
//! argument and result types §6 names, as JSON-schema'd DTOs.
//!
//! # Why these are separate types, not `#[derive(Serialize)]` on the
//! domain types
//!
//! [`BoardRow`], [`IssueSnapshot`] and the [`crate::vcs`] enums they
//! carry are this crate's *internal* vocabulary: `board.rs`'s doc already
//! draws the line that the `board` tool "returns data" while the
//! coordinator agent renders it, and `state/mod.rs` records that its
//! label prefixes are hard-coded pending the workflow parser. Deriving
//! `Serialize`/`JsonSchema` directly on them would publish every one of
//! those internal shapes — field names, enum variant names, and all — as
//! a frozen MCP contract, so a rename inside the crate would silently
//! become a breaking protocol change for every connected agent. The
//! mapping below is the seam where that gets decided on purpose.
//!
//! The schemas are generated by `schemars`, which this crate reaches
//! through `rmcp::schemars` rather than a direct dependency (see
//! `Cargo.toml`) so the derive and the `rmcp` macros can never disagree
//! about a schemars version.

use rmcp::schemars;
use serde::{Deserialize, Serialize};

use crate::board::BoardRow;
use crate::state::{IssueSnapshot, Priority};
use crate::vcs::{
    CiConclusion, IssueRelationships, IssueState, PullRequestState,
    PullRequestStatus,
};

// ---------------------------------------------------------------------
// register (§6 "Registration & lifecycle")
// ---------------------------------------------------------------------

/// Arguments to `register(worker_ref, role, cwd?, spawn_token?)` (§6).
#[derive(Clone, Debug, Deserialize, schemars::JsonSchema)]
pub struct RegisterArgs {
    /// The connecting agent's own reference for itself (§2.6). Recorded
    /// and echoed back; nothing keys off it yet.
    pub worker_ref: String,

    /// The agent's role (§2.6's roster: `coordinator`, `issue-lead`,
    /// `developer`, ...). Deliberately a free-form string, not an enum:
    /// §2.6 calls roles "labels the server keys instructions on" and
    /// says repos "add or drop roles/lenses via config", so a closed set
    /// here would reject a repo-defined role the spec explicitly allows.
    pub role: String,

    /// The directory the client was launched in — required for a
    /// coordinator, which has no `spawn_token` and binds its project
    /// from this path (§2.5, §6). Must be absolute: HTTP/SSE carries no
    /// client working directory, so the server has nothing to resolve a
    /// relative path against.
    #[serde(default)]
    pub cwd: Option<String>,

    /// A spawned phase process's one-time correlation token (§2.6).
    /// **Not implemented in this slice** — supplying one is rejected
    /// rather than ignored; see `src/server/mod.rs`'s module doc for the
    /// full list of what this slice leaves out and why.
    #[serde(default)]
    pub spawn_token: Option<String>,
}

/// What `register` returns once the connection is bound (§6).
#[derive(Clone, Debug, Serialize, schemars::JsonSchema)]
pub struct RegisterResult {
    /// The project handle this connection is now bound to for its life
    /// (§2.5, §15) — `ProjectPointer::name`, set at `init`.
    pub project: String,

    /// That project's GitHub repo slug (`owner/repo`).
    pub repo: String,

    /// That project's container directory (§10.1).
    pub project_dir: String,

    /// The role echoed back, so the client can confirm what the server
    /// recorded.
    pub role: String,

    /// The `worker_ref` echoed back.
    pub worker_ref: String,
}

// ---------------------------------------------------------------------
// board (§6 "Board / status", §13)
// ---------------------------------------------------------------------

/// Arguments to `board(filter?)` (§6, §13).
#[derive(Clone, Debug, Default, Deserialize, schemars::JsonSchema)]
pub struct BoardArgs {
    /// **Unimplemented in this slice.** §6 gives `filter` no shape at
    /// all, and every plausible reading (a label expression, a phase
    /// name, a free-text query) would need a different `gh issue list`
    /// argument or a different post-filter. Accepted so a client passing
    /// one gets a clear rejection instead of silently receiving an
    /// unfiltered board it believes is filtered — see
    /// `src/server/mod.rs`'s module doc.
    #[serde(default)]
    pub filter: Option<String>,
}

/// The orchestration board (§13) for the connection's bound project.
#[derive(Clone, Debug, Serialize, schemars::JsonSchema)]
pub struct BoardResult {
    /// The bound project's handle.
    pub project: String,

    /// The bound project's repo slug.
    pub repo: String,

    /// One row per open issue, ordered by issue number
    /// ([`crate::board::build_board`]).
    pub rows: Vec<BoardRowWire>,

    /// How many open issues the server was willing to page in
    /// ([`crate::BOARD_ISSUE_LIMIT`]).
    pub issue_limit: u32,

    /// Whether the repo had at least `issue_limit` open issues, i.e.
    /// whether this board may be missing rows. Reported rather than left
    /// implicit: §15's "surface, don't bury" makes a silently truncated
    /// board — which reads exactly like a shorter queue — the wrong
    /// failure mode.
    pub truncated: bool,
}

/// One board row (§13) — the wire form of [`BoardRow`].
#[derive(Clone, Debug, Serialize, schemars::JsonSchema)]
pub struct BoardRowWire {
    /// The issue number (scoped to `repo`, §15).
    pub number: u64,
    /// The issue title.
    pub title: String,
    /// The issue's GitHub URL, so the client can render §15's mandatory
    /// clickable `[#N (title)](url)` link without deriving it.
    pub url: String,
    /// Whether the issue is open or closed.
    pub state: IssueStateWire,
    /// The current workflow phase (`status:<phase>`), if labelled.
    pub status: Option<String>,
    /// The issue's priority label, if any.
    pub priority: Option<PriorityWire>,
    /// Phases still gated on a human decision on this issue (§4.3).
    pub gates: Vec<String>,
    /// Phases already approved on this issue (§4.3).
    pub approvals: Vec<String>,
    /// The claiming instance's id (§8.2), if the issue is claimed.
    pub owner: Option<String>,
    /// Dependency/hierarchy edges (§8.4).
    pub relationships: RelationshipsWire,
    /// The most relevant linked pull request's signals, if any.
    pub pull_request: Option<PullRequestStatusWire>,
}

